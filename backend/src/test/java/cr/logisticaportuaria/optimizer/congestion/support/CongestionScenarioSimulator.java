package cr.logisticaportuaria.optimizer.congestion.support;

import cr.logisticaportuaria.optimizer.congestion.domain.CostaRicaCalendar;
import cr.logisticaportuaria.optimizer.congestion.domain.GateHistory;
import cr.logisticaportuaria.optimizer.congestion.domain.HistoricalVisit;
import java.time.DayOfWeek;
import java.time.Duration;
import java.time.Instant;
import java.time.ZonedDateTime;
import java.time.temporal.ChronoUnit;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.PriorityQueue;
import java.util.Random;
import java.util.UUID;

/**
 * Discrete-event simulator of one gate, used as the synthetic history of the congestion
 * module (there is no real history in the repository).
 *
 * <p>Model, fully deterministic for a fixed seed:
 *
 * <ul>
 *   <li>Arrivals: non-homogeneous Poisson process generated by thinning, with a piecewise
 *       rate (per hour) over the base rate: morning peak 07:00-10:00 &times;2.0, afternoon
 *       peak 15:00-18:00 &times;1.7, night 22:00-06:00 &times;0.1, weekend &times;0.6 and
 *       national holiday &times;0.3.</li>
 *   <li>Service: lognormal with the requested mean and sigma, drawn for every truck.</li>
 *   <li>Queue: FIFO with {@code lanes} identical servers (event driven).</li>
 *   <li>Appointments: 60 % of the trucks have an appointment at their arrival time, so
 *       the feature "appointments in the next hour" carries real information.</li>
 * </ul>
 *
 * <p>Parameters and seed are written by the regression test in
 * {@code docs/experiments/EXP-005-congestion/}.
 */
public final class CongestionScenarioSimulator {

    private static final double MORNING_PEAK = 2.0;
    private static final double AFTERNOON_PEAK = 1.7;
    private static final double NIGHT_FACTOR = 0.1;
    private static final double WEEKEND_FACTOR = 0.6;
    private static final double HOLIDAY_FACTOR = 0.3;
    private static final double APPOINTMENT_SHARE = 0.6;

    private CongestionScenarioSimulator() {
    }

    /**
     * Parameters of the simulation.
     *
     * @param lanes              servers of the gate
     * @param meanServiceMinutes mean service time per truck
     * @param serviceSigma       sigma of the underlying normal (lognormal service times)
     * @param baseArrivalsPerHour base arrival rate of a working day (the profile multiplies it)
     * @param seed               seed of the random generator
     */
    public record Parameters(int lanes, double meanServiceMinutes, double serviceSigma,
            double baseArrivalsPerHour, long seed) {

        /** Validates the parameters. */
        public Parameters {
            if (lanes <= 0 || meanServiceMinutes <= 0.0 || serviceSigma < 0.0 || baseArrivalsPerHour < 0.0) {
                throw new IllegalArgumentException("invalid simulation parameters");
            }
        }

        /** @return the parameters of the reference scenario of the experiment */
        public static Parameters reference() {
            return new Parameters(3, 7.0, 0.3, 18.0, 2026L);
        }
    }

    /**
     * Result of the simulation.
     *
     * @param history the history ready for the forecaster
     * @param visits  the closed visits, oldest first
     */
    public record Simulation(GateHistory history, List<HistoricalVisit> visits) {
    }

    /**
     * Simulates the gate.
     *
     * @param gateId     identifier of the gate
     * @param yardId     identifier of the yard
     * @param gateCode   code of the gate
     * @param start      start of the window (inclusive)
     * @param days       length of the window in days
     * @param parameters parameters of the simulation
     * @return the simulated history
     */
    public static Simulation simulate(UUID gateId, UUID yardId, String gateCode, Instant start, int days,
            Parameters parameters) {
        if (days <= 0) {
            throw new IllegalArgumentException("days must be positive");
        }
        Instant end = start.plus(days, ChronoUnit.DAYS);
        List<Instant> arrivals = arrivals(start, end, parameters);
        Random random = new Random(parameters.seed());
        PriorityQueue<Double> busyUntil = new PriorityQueue<>();
        List<HistoricalVisit> visits = new ArrayList<>();
        List<Instant> appointments = new ArrayList<>();
        Instant origin = arrivals.isEmpty() ? start : arrivals.get(0);
        for (Instant arrival : arrivals) {
            double arrivalMinute = Duration.between(origin, arrival).toMillis() / 60_000.0;
            while (!busyUntil.isEmpty() && busyUntil.peek() <= arrivalMinute) {
                busyUntil.poll();
            }
            double serviceStart;
            if (busyUntil.size() < parameters.lanes()) {
                serviceStart = arrivalMinute;
            } else {
                serviceStart = busyUntil.poll();
            }
            double service = lognormal(parameters.meanServiceMinutes(), parameters.serviceSigma(), random);
            double serviceEnd = serviceStart + service;
            busyUntil.add(serviceEnd);
            Instant exit = origin.plusSeconds(Math.round(serviceEnd * 60.0));
            visits.add(new HistoricalVisit(arrival, exit, Math.max(0.0, serviceStart - arrivalMinute), service));
            if (random.nextDouble() < APPOINTMENT_SHARE) {
                appointments.add(arrival);
            }
        }
        visits.sort(Comparator.comparing(HistoricalVisit::enteredAt));
        appointments.sort(Comparator.naturalOrder());
        GateHistory history = new GateHistory(gateId, yardId, gateCode, parameters.lanes(), visits, appointments, 0);
        return new Simulation(history, List.copyOf(visits));
    }

    /**
     * Arrival rate of an instant, in trucks per hour.
     *
     * @param instant any instant
     * @param base    base rate of a working day at midday
     * @return the rate
     */
    public static double ratePerHour(Instant instant, double base) {
        ZonedDateTime local = instant.atZone(CostaRicaCalendar.ZONE);
        int hour = local.getHour();
        double factor;
        if (hour >= 7 && hour < 10) {
            factor = MORNING_PEAK;
        } else if (hour >= 15 && hour < 18) {
            factor = AFTERNOON_PEAK;
        } else if (hour >= 22 || hour < 6) {
            factor = NIGHT_FACTOR;
        } else {
            factor = 1.0;
        }
        DayOfWeek day = local.getDayOfWeek();
        if (day == DayOfWeek.SATURDAY || day == DayOfWeek.SUNDAY) {
            factor *= WEEKEND_FACTOR;
        }
        if (CostaRicaCalendar.isHoliday(local.toLocalDate())) {
            factor *= HOLIDAY_FACTOR;
        }
        return base * factor;
    }

    private static List<Instant> arrivals(Instant start, Instant end, Parameters parameters) {
        List<Instant> arrivals = new ArrayList<>();
        double base = parameters.baseArrivalsPerHour();
        if (base <= 0.0) {
            return arrivals;
        }
        double maxRatePerHour = base * MORNING_PEAK;
        double maxRatePerMinute = maxRatePerHour / 60.0;
        Random random = new Random(parameters.seed());
        Instant cursor = start;
        while (true) {
            double u = random.nextDouble();
            double gapMinutes = -Math.log(1.0 - u) / maxRatePerMinute;
            cursor = cursor.plusSeconds(Math.round(gapMinutes * 60.0));
            if (!cursor.isBefore(end)) {
                return arrivals;
            }
            double rate = ratePerHour(cursor, base);
            if (random.nextDouble() * maxRatePerHour < rate) {
                arrivals.add(cursor);
            }
        }
    }

    private static double lognormal(double mean, double sigma, Random random) {
        double mu = Math.log(mean) - sigma * sigma / 2.0;
        return Math.min(120.0, Math.exp(mu + sigma * random.nextGaussian()));
    }
}
